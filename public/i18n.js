export function translate(lang, key, params) {
  const dict = STRINGS[lang] ?? STRINGS[DEFAULT_LANG];
  let s = dict[key];
  if (s == null) s = STRINGS[DEFAULT_LANG][key] ?? key;
  if (typeof s !== 'string' || !params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
}
